// Media load generator: one or more MediaMTX processes on their own API ports, every viewer is a path whose source is
// the target's WHEP URL, so each viewer is a real WebRTC peer (ICE, DTLS-SRTP, RTCP) that receives and depacketizes H.264
// and Opus without decoding. Viewers are added and removed at runtime through the MediaMTX API.
import { writeFileSync, createWriteStream } from 'node:fs';
import { join } from 'node:path';
import { bin, run, onLines, fetchJson, sleep } from './common.mjs';

const LOG_CAP = 10 * 2 ** 20;  // WAR/ERR lines kept per instance (results folder); at 1000 viewers loss warnings alone can be large

function config(o, port) {
  return [
    '# Generated by tools/load (load generator; every server is off, only the API listens).',
    'logLevel: info', 'logDestinations: [stdout]', 'readTimeout: 10s', 'writeTimeout: 10s',
    // A larger receive buffer than the OS default: a 1080p keyframe arrives as a burst of ~100+ packets per viewer.
    `udpReadBufferSize: ${o.udpReadBufferSize ?? 4194304}`,
    'authInternalUsers:', "  - user: any\n    pass:\n    ips: ['127.0.0.1', '::1']\n    permissions:\n      - action: api",
    'api: true', `apiAddress: 127.0.0.1:${port}`, 'metrics: false', 'pprof: false', 'playback: false',
    'rtsp: false', 'rtmp: false', 'hls: false', 'srt: false', 'moq: false', 'webrtc: false',
    'pathDefaults:', `  whepHandshakeTimeout: ${o.handshakeTimeout || '10s'}`, `  whepTrackGatherTimeout: ${o.trackGatherTimeout || '2s'}`,
    ...(o.bearerToken ? [`  whepBearerToken: ${JSON.stringify(o.bearerToken)}`] : []),
    'paths: {}',
  ].join('\n') + '\n';
}

export class Generator {
  constructor(o) {
    this.o = o;
    this.instances = [];
    this.loss = new Map();          // viewer -> RTP packets reported lost by the WebRTC source
    this.procErrors = new Map();    // viewer -> depacketizer/processing errors
    this.sourceErrors = new Map();  // viewer -> [messages]
    this.pairs = new Map();         // viewer -> "local -> remote" ICE pair
    this.errorKinds = {};           // normalised ERR message -> count (written to results.json)
    this.lossLines = 0;
  }

  async start() {
    const n = Math.max(1, this.o.instances || 1);
    for (let i = 0; i < n; i++) {
      const port = (this.o.apiPortBase || 21900) + i, file = join(this.o.dir, `generator-${i}.yml`);
      writeFileSync(file, config(this.o, port));
      const proc = run(bin.mediamtx, [file], { cwd: this.o.dir });
      const log = createWriteStream(join(this.o.dir, `generator-${i}.log`));
      let logged = 0;
      const inst = { index: i, port, proc, api: `http://127.0.0.1:${port}`, exited: null };
      proc.once('exit', code => { inst.exited = code; });
      const onLine = line => {
        this.parse(line);
        if (!/ (WAR|ERR) /.test(line) || logged > LOG_CAP) return;
        logged += line.length + 1;
        log.write(line + '\n');
      };
      onLines(proc.stdout, onLine);
      onLines(proc.stderr, onLine);
      this.instances.push(inst);
    }
    for (const inst of this.instances) {
      let ok = false;
      for (let t = 0; t < 50 && !ok; t++) { try { ok = (await fetchJson(`${inst.api}/v3/paths/list`, {}, 1000)).ok; } catch { await sleep(200); } }
      if (!ok) throw new Error(`generator instance ${inst.index} API did not start on ${inst.port}`);
    }
  }

  parse(line) {
    let m;
    // MediaMTX writes "1 RTP packet lost" and "N RTP packets lost": both count.
    if ((m = line.match(/\[path ([^\]]+)\] \[WebRTC source\] (\d+) RTP packets? lost/))) { this.loss.set(m[1], (this.loss.get(m[1]) || 0) + Number(m[2])); this.lossLines++; }
    else if ((m = line.match(/\[path ([^\]]+)\] (\d+) processing errors?/))) this.procErrors.set(m[1], (this.procErrors.get(m[1]) || 0) + Number(m[2]));
    else if ((m = line.match(/\[path ([^\]]+)\] \[WebRTC source\] peer connection established, local candidate: (\S+), remote candidate: (\S+)/))) this.pairs.set(m[1], `${m[2]} -> ${m[3]}`);
    else if ((m = line.match(/ ERR \[path ([^\]]+)\] \[WebRTC source\] (.*)$/))) {
      const list = this.sourceErrors.get(m[1]) || [];
      list.push(`${line.slice(0, 19)} ${m[2]}`.slice(0, 300));
      this.sourceErrors.set(m[1], list.slice(-5));
      const kind = m[2].replace(/[0-9a-f]{8}-[0-9a-f-]{27}/g, '<id>').replace(/\d+/g, 'N').slice(0, 120);
      this.errorKinds[kind] = (this.errorKinds[kind] || 0) + 1;
    }
  }

  // MediaMTX's WHEP source wants whep:// (http) or wheps:// (https) URLs.
  static sourceUrl(httpUrl) { return httpUrl.replace(/^http:/, 'whep:').replace(/^https:/, 'wheps:'); }

  async add(name, url, index) {
    const inst = this.instances[index % this.instances.length], t0 = Date.now();
    try {
      const r = await fetchJson(`${inst.api}/v3/config/paths/add/${name}`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ source: Generator.sourceUrl(url) }) }, 30000);
      return { ok: r.ok, status: r.status, t0, apiMs: Date.now() - t0, error: r.ok ? null : JSON.stringify(r.body).slice(0, 200) };
    } catch (e) {
      return { ok: false, status: 0, t0, apiMs: Date.now() - t0, error: e.message };
    }
  }

  // Replaces a viewer's source: MediaMTX restarts the WebRTC source (the old WHEP session is deleted, a new one is made),
  // i.e. a mid-session quality change of the same viewer.
  async setSource(name, url, index) {
    const inst = this.instances[index % this.instances.length], t0 = Date.now();
    try {
      const r = await fetchJson(`${inst.api}/v3/config/paths/patch/${name}`, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ source: Generator.sourceUrl(url) }) }, 30000);
      return { ok: r.ok, status: r.status, apiMs: Date.now() - t0, error: r.ok ? null : JSON.stringify(r.body).slice(0, 200) };
    } catch (e) { return { ok: false, status: 0, apiMs: Date.now() - t0, error: e.message }; }
  }

  async remove(name, index) {
    const inst = this.instances[index % this.instances.length];
    try { return (await fetchJson(`${inst.api}/v3/config/paths/delete/${name}`, { method: 'DELETE' }, 30000)).ok; } catch { return false; }
  }

  // All paths of every instance (paged; MediaMTX defaults to 100 items per page). `failed` holds the instances whose list
  // did not answer: their viewers must not be read as disconnected in that sample.
  async list() {
    const out = new Map(), failed = new Set();
    let ok = true;
    await Promise.all(this.instances.map(async inst => {
      try {
        for (let page = 0, pages = 1; page < pages; page++) {
          const r = await fetchJson(`${inst.api}/v3/paths/list?itemsPerPage=1000&page=${page}`, {}, 10000);
          if (!r.ok) throw new Error(`status ${r.status}`);
          pages = r.body.pageCount || 1;
          for (const item of r.body.items || []) out.set(item.name, item);
        }
      } catch { ok = false; failed.add(inst.index); }
    }));
    return { ok, items: out, failed };
  }

  pids() { return this.instances.map(i => i.proc.pid); }
  dead() { return this.instances.filter(i => i.exited !== null).map(i => i.index); }
  stop() { for (const i of this.instances) if (i.proc.exitCode === null) i.proc.kill(); }
}
