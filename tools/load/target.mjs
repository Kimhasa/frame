// Standalone load target that mirrors FRAME Console's media path without running the app: MediaMTX with the streaming
// settings streamer.cpp generates, FFmpeg publishing testsrc2 with the app's H.264 (High, no B-frames, 1 s GOP) and Opus
// arguments, optional on-demand lower qualities and DVR recording, and the app-shim for /info, WHEP proxy, /chat and /dvr.
// With --source live every frame carries a wall-clock barcode (tools/motion-test.html format) for the browser latency.
// usage: node tools/load/target.mjs [--config target.json] [--mbps 8 --fps 60 --size 1920x1080 --renditions 720p,480p --record]
// Stops on Ctrl+C, on "q" + Enter, or after --duration seconds. Writes <dir>/state.json (PIDs, ports, URLs) for the runner.
import { mkdirSync, writeFileSync, appendFileSync, existsSync, renameSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { bin, parseArgs, readJson, merge, run, onLines, killOnExit, killAll, sleep, fetchJson, toolVersion, portFree } from './lib/common.mjs';
import { startShim } from './lib/app-shim.mjs';

const defaults = {
  dir: '', path: 'screen-01', size: '1920x1080', fps: 60, mbps: 8, audioKbps: 128, encoder: 'h264_nvenc', rateControl: 'cbr',
  rtspPort: 21554, webrtcPort: 21889, icePort: 21189, apiPort: 21997, playbackPort: 21996, shimPort: 21888,
  webrtcBind: '127.0.0.1',  // the app binds MediaMTX's WHEP server to loopback behind its proxy; 0.0.0.0 lets remote generators use it directly
  // The shim (test picture, chat, DVR, /api/stats) listens on loopback only; --shim-bind 0.0.0.0 opens it for a generator on another PC.
  shimBind: '127.0.0.1', interfaces: '', additionalHosts: '', renditions: '', record: false, barcode: true, shim: true, duration: 0,
  source: 'clip', clipSec: 20,  // see publisherArgs
  // Shim limits = app source of 2026-10-28: chat.cpp kMaxClients 2000, http_server.cpp kMaxThreads 2600 / kMaxRequests 400
  // (c54c07d had 300 chat / 400 connections: --chat-limit 300 --http-limit 400). chatNames: app | strict (see app-shim.mjs).
  chatLimit: 2000, httpLimit: 2600, requestLimit: 400, chatNames: 'app',
};

const args = parseArgs(process.argv.slice(2));
const { _, config, ...cli } = args;
const o = merge(merge(defaults, config ? readJson(config) : {}), cli);
o.dir ||= join(tmpdir(), `frame-load-target-${Date.now()}`);
mkdirSync(o.dir, { recursive: true });
const [W, H] = String(o.size).split('x').map(Number);

// Same as AutoBitrateMbps in native/src/config.cpp (rendition caps follow the source like the app's ladder).
const autoMbps = (w, h, fps, enc) => Math.min(200, Math.max(0.5, Math.round(0.07 * w * h * 60 * Math.pow((fps >= 30 ? fps : 60) / 60, 0.75) * (enc === 'libx264' ? 0.85 : 1) / 1e6 * 2) / 2));
o.renditionList = String(o.renditions || '').split(',').filter(Boolean).map(name => {
  const h = parseInt(name, 10), w = Math.round(W * h / H) & ~1;
  return { name, width: w, height: h, mbps: Math.min(o.mbps, autoMbps(w, h, o.fps, o.encoder)) };
}).filter(r => r.height < H);

// Mirrors VideoEncoderArgs in native/src/streamer.cpp.
function videoArgs(encoder, fps, mbps, rc) {
  const kbps = `${Math.round(mbps * 1000)}k`, gop = String(fps);
  let a;
  if (encoder === 'h264_nvenc') {
    a = ['-c:v', 'h264_nvenc', '-preset', 'p4', '-tune', 'll', '-profile:v', 'high', '-zerolatency', '1', '-delay', '0', '-rc-lookahead', '0', '-no-scenecut', '1', '-forced-idr', '1', '-spatial-aq', '1', '-aq-strength', '8'];
    a.push(...(rc === 'vbr' ? ['-rc', 'vbr', '-cq', '23', '-b:v', '0', '-maxrate', kbps, '-bufsize', kbps] : ['-rc', 'cbr', '-b:v', kbps, '-maxrate', kbps, '-bufsize', kbps]));
  } else {
    a = ['-c:v', 'libx264', '-preset', fps > 90 ? 'superfast' : 'veryfast', '-tune', 'zerolatency', '-profile:v', 'high', '-sc_threshold', '0'];
    a.push(...(rc === 'vbr' ? ['-crf', '23', '-maxrate', kbps, '-bufsize', kbps] : ['-b:v', kbps, '-maxrate', kbps, '-bufsize', kbps]));
  }
  return [...a, '-bf', '0', '-g', gop, '-keyint_min', gop, '-pix_fmt', 'nv12', '-colorspace', 'bt709', '-color_primaries', 'bt709', '-color_trc', 'bt709', '-color_range', 'tv'];
}

// YAML values are written as JSON strings (valid YAML double-quoted scalars); the on-demand command is split by MediaMTX like a POSIX shell.
const q = s => JSON.stringify(String(s));
const sh = s => `'${String(s).replace(/'/g, "'\\''")}'`;
const list = s => `[${String(s || '').split(',').filter(Boolean).map(v => q(v.trim())).join(', ')}]`;

function mediamtxConfig() {
  const y = [
    '# Generated by tools/load/target.mjs (same streaming settings as native/src/streamer.cpp, own ports).',
    'logLevel: info', 'logDestinations: [stdout]', 'readTimeout: 10s', 'writeTimeout: 10s', 'writeQueueSize: 2048',
    'authInternalUsers:',
    "  - user: any\n    pass:\n    ips: ['127.0.0.1', '::1']\n    permissions:\n      - action: publish\n      - action: read\n      - action: api\n      - action: playback",
    '  - user: any\n    pass:\n    ips: []\n    permissions:\n      - action: read',
    `api: true`, `apiAddress: 127.0.0.1:${o.apiPort}`, 'metrics: false', 'pprof: false',
    `playback: ${o.record ? 'true' : 'false'}`, `playbackAddress: 127.0.0.1:${o.playbackPort}`,
    'rtsp: true', 'rtspTransports: [tcp]', 'rtspEncryption: "no"', `rtspAddress: 127.0.0.1:${o.rtspPort}`,
    'rtmp: false', 'hls: false', 'srt: false', 'moq: false',
    'webrtc: true', `webrtcAddress: ${o.webrtcBind}:${o.webrtcPort}`, 'webrtcEncryption: false', "webrtcAllowOrigins: ['*']", "webrtcTrustedProxies: ['127.0.0.1']",
    `webrtcLocalUDPAddress: ':${o.icePort}'`, "webrtcLocalTCPAddress: ''", 'webrtcIPsFromInterfaces: true',
    `webrtcIPsFromInterfacesList: ${list(o.interfaces)}`, `webrtcAdditionalHosts: ${list(o.additionalHosts)}`, 'webrtcICEServers2: []',
    'paths:', `  ${q(o.path)}:`, '    source: publisher',
  ];
  if (o.record) y.push(`    record: true`, `    recordPath: ${q(join(o.dir, 'rec', '%path', '%Y-%m-%d_%H-%M-%S-%f').replace(/\\/g, '/'))}`, '    recordFormat: fmp4',
    '    recordPartDuration: 1s', '    recordMaxPartSize: 100M', '    recordSegmentDuration: 60s', '    recordDeleteAfter: 0s');
  for (const r of o.renditionList) {
    const cmd = `${sh(bin.ffmpeg.replace(/\\/g, '/'))} -hide_banner -nostdin -loglevel warning -rtsp_transport tcp -i rtsp://127.0.0.1:$RTSP_PORT/${o.path} -map 0:v:0 -map 0:a? -vf scale=${r.width}:${r.height}:flags=bilinear ` +
      videoArgs(o.encoder, o.fps, r.mbps, o.rateControl).join(' ') + ' -c:a copy -f rtsp -rtsp_transport tcp -pkt_size 1200 rtsp://127.0.0.1:$RTSP_PORT/$MTX_PATH';
    y.push(`  ${q(o.path + '/' + r.name)}:`, `    runOnDemand: ${q(cmd)}`, '    runOnDemandStartTimeout: 15s', '    runOnDemandCloseAfter: 10s');
  }
  return y.join('\n') + '\n';
}

// testsrc2 (moving pattern) with the frame's wall-clock time as a barcode strip across the top: 16 cells, 4 markers
// (white, black, white, black) then 12 bits of epoch ms % 4000. setpts=RTCTIME stamps each frame when it is generated.
function videoFilter() {
  const bh = Math.max(16, Math.round(H / 40));
  const bit = "if(lt(X,4),if(mod(X,2),16,235),if(mod(floor(mod(floor(T*1000),4000)/pow(2,15-X)),2),235,16))";
  if (!o.barcode) return `[0:v]format=nv12[v]`;
  return `[0:v]format=yuv420p,settb=1/1000,setpts=RTCTIME/1000,split[m][s];[s]crop=16:2:0:0,geq=lum='${bit}':cb=128:cr=128,scale=${W}:${bh}:flags=neighbor[bar];` +
    `[m][bar]overlay=0:0,setpts=N/${o.fps}/TB,format=nv12[v]`;
}

const audioArgs = () => ['-c:a', 'libopus', '-b:a', `${o.audioKbps}k`, '-ac', '2', '-application', 'lowdelay', '-frame_duration', '10'];
const rtspOut = () => ['-f', 'rtsp', '-rtsp_transport', 'tcp', '-pkt_size', '1200', `rtsp://127.0.0.1:${o.rtspPort}/${o.path}`];

// source "live": testsrc2 encoded in real time with the barcode (~2 CPU cores for 1080p60 generation on a laptop).
// source "clip": the same testsrc2 encoded once with the app's arguments and looped with stream copy, so the publisher costs
// almost nothing and the host's CPU goes to MediaMTX and the viewers, as with the app's GPU encoder. No live barcode.
// h264_mp4toannexb puts SPS/PPS in band before every IDR (MP4 keeps them only in the header), like a live encoder.
function publisherArgs() {
  const head = ['-hide_banner', '-nostdin', '-loglevel', 'warning', '-nostats', '-progress', 'pipe:1', '-stats_period', '5'];
  if (o.source === 'clip') return [...head, '-re', '-stream_loop', '-1', '-i', clipFile, '-map', '0:v', '-map', '0:a', '-c', 'copy', '-bsf:v', 'h264_mp4toannexb', ...rtspOut()];
  return [...head, '-re', '-f', 'lavfi', '-i', `testsrc2=size=${W}x${H}:rate=${o.fps}`, '-re', '-f', 'lavfi', '-i', 'sine=frequency=440:sample_rate=48000',
    '-filter_complex', videoFilter(), '-map', '[v]', '-map', '1:a', ...videoArgs(o.encoder, o.fps, o.mbps, o.rateControl), ...audioArgs(), ...rtspOut()];
}

const clipFile = join(tmpdir(), 'frame-load-clips', `testsrc2-${W}x${H}-${o.fps}fps-${o.mbps}M-${o.encoder}-${o.rateControl}-${o.clipSec}s.mp4`);
function ensureClip() {
  if (o.source !== 'clip') return null;
  if (!existsSync(clipFile)) {
    mkdirSync(dirname(clipFile), { recursive: true });
    const r = spawnSync(bin.ffmpeg, ['-hide_banner', '-loglevel', 'error', '-y', '-f', 'lavfi', '-i', `testsrc2=size=${W}x${H}:rate=${o.fps}`, '-f', 'lavfi', '-i', 'sine=frequency=440:sample_rate=48000',
      '-t', String(o.clipSec), '-map', '0:v', '-map', '1:a', '-vf', 'format=nv12', ...videoArgs(o.encoder, o.fps, o.mbps, o.rateControl), ...audioArgs(), clipFile + '.tmp.mp4'], { encoding: 'utf8', windowsHide: true });
    if (r.status !== 0) { console.log(JSON.stringify({ event: 'target-failed', reason: 'clip encode failed', detail: (r.stderr || '').slice(-500) })); process.exit(1); }
    renameSync(clipFile + '.tmp.mp4', clipFile);
  }
  // Evidence of what is published: codec/profile, B-frames, keyframe spacing and the real bitrate of the looped clip.
  const p = spawnSync(bin.ffprobe, ['-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=codec_name,profile,width,height,r_frame_rate,has_b_frames,bit_rate:format=bit_rate,duration', '-of', 'json', clipFile], { encoding: 'utf8', windowsHide: true });
  const k = spawnSync(bin.ffprobe, ['-v', 'error', '-select_streams', 'v:0', '-skip_frame', 'nokey', '-show_entries', 'frame=pts_time', '-of', 'csv=p=0', clipFile], { encoding: 'utf8', windowsHide: true });
  const keys = String(k.stdout || '').trim().split(/\r?\n/).map(Number).filter(Number.isFinite);
  let probe = null;
  try { probe = JSON.parse(p.stdout); } catch {}
  return { file: clipFile, probe, keyframeIntervalSec: keys.length > 1 ? +((keys[keys.length - 1] - keys[0]) / (keys.length - 1)).toFixed(3) : null };
}

let stopping = false, state = null, shim = null, pub = null, publisherRestarts = -1;
function saveState() { if (state) writeFileSync(join(o.dir, 'state.json'), JSON.stringify(state, null, 2)); }
function stop(reason) {
  if (stopping) return;
  stopping = true;
  if (state) Object.assign(state, { stoppedAt: new Date().toISOString(), stopReason: reason, publisherRestarts, shimStats: shim?.stats || null, mediamtxLog: mtxStats });
  saveState();
  shim?.close();
  killAll();
  console.log(JSON.stringify({ event: 'target-stopped', reason }));
  process.exit(reason === 'duration' || reason === 'stdin' ? 0 : 1);
}

killOnExit();
const busy = [];
for (const [port, type] of [[o.rtspPort, 'tcp'], [o.webrtcPort, 'tcp'], [o.apiPort, 'tcp'], [o.playbackPort, 'tcp'], [o.icePort, 'udp'], ...(o.shim ? [[o.shimPort, 'tcp']] : [])])
  if (!(await portFree(port, type, type === 'udp' ? '0.0.0.0' : port === o.shimPort ? o.shimBind : '127.0.0.1'))) busy.push(`${type}/${port}`);
if (busy.length) { console.log(JSON.stringify({ event: 'target-failed', reason: 'ports in use', busy })); process.exit(1); }
const clip = ensureClip();
writeFileSync(join(o.dir, 'mediamtx.yml'), mediamtxConfig());
const mtxLog = join(o.dir, 'mediamtx.log');
const mtx = run(bin.mediamtx, [join(o.dir, 'mediamtx.yml')], { cwd: o.dir });
// Under overload MediaMTX logs "reader is too slow" per session every second (hundreds of MB per hour): those are
// counted instead of written, and the log itself is capped.
const mtxStats = { tooSlowWarnings: 0, discardedFramesLogged: 0, logBytes: 0, logDropped: 0 };
const mtxLine = line => {
  const slow = line.match(/reader is too slow, discarding (\d+) frames/);
  if (slow) { mtxStats.tooSlowWarnings++; mtxStats.discardedFramesLogged += Number(slow[1]); return; }
  if (mtxStats.logBytes > 20 * 2 ** 20) { mtxStats.logDropped++; return; }
  mtxStats.logBytes += line.length + 1;
  appendFileSync(mtxLog, line + '\n');
};
onLines(mtx.stdout, mtxLine);
onLines(mtx.stderr, mtxLine);
mtx.once('exit', code => stop(`mediamtx exited ${code}`));
for (let i = 0; i < 50; i++) { try { if ((await fetchJson(`http://127.0.0.1:${o.apiPort}/v3/paths/list`, {}, 1000)).ok) break; } catch {} await sleep(200); }

const pubLog = join(o.dir, 'publisher.log'), progressFile = join(o.dir, 'publisher-progress.jsonl');
function startPublisher() {
  publisherRestarts++;
  let progress = {};
  pub = run(bin.ffmpeg, publisherArgs(), { cwd: o.dir });
  onLines(pub.stdout, line => {
    const [k, v] = line.split('=');
    progress[k] = v;
    if (k === 'progress') { appendFileSync(progressFile, JSON.stringify({ t: Date.now(), fps: +progress.fps, bitrate: progress.bitrate, speed: progress.speed, frame: +progress.frame, drop: +progress.drop_frames, dup: +progress.dup_frames }) + '\n'); progress = {}; }
  });
  onLines(pub.stderr, line => appendFileSync(pubLog, line + '\n'));
  pub.once('exit', code => { appendFileSync(pubLog, `publisher exited ${code}\n`); if (!stopping) setTimeout(startPublisher, 1000); });
}
startPublisher();

let ready = false;
for (let i = 0; i < 100 && !ready; i++) { await sleep(200); try { ready = !!(await fetchJson(`http://127.0.0.1:${o.apiPort}/v3/paths/get/${o.path}`, {}, 1000)).body?.ready; } catch {} }
shim = o.shim ? await startShim({ ...o, port: o.shimPort, bind: o.shimBind, width: W, height: H, maxChat: o.chatLimit, maxHttp: o.httpLimit, maxRequests: o.requestLimit, chatNames: o.chatNames, discardWarnings: () => mtxStats.tooSlowWarnings }) : null;

state = {
  startedAt: new Date().toISOString(), dir: o.dir, options: o, ready, clip, barcode: o.source === 'live' && o.barcode,
  pids: { mediamtx: mtx.pid, publisher: pub.pid, shim: shim ? process.pid : null },
  versions: { mediamtx: toolVersion(bin.mediamtx, ['--version']), ffmpeg: toolVersion(bin.ffmpeg) },
  urls: {
    whepDirect: `http://127.0.0.1:${o.webrtcPort}/{stream}/whep`, whepProxy: shim ? `http://127.0.0.1:${o.shimPort}/{stream}/whep` : null,
    base: shim ? `http://127.0.0.1:${o.shimPort}` : null, viewerPage: shim ? `http://127.0.0.1:${o.shimPort}/${o.path}` : null,
    mediamtxPage: `http://127.0.0.1:${o.webrtcPort}/${o.path}/`, api: `http://127.0.0.1:${o.apiPort}`,
    appStats: shim ? `http://127.0.0.1:${o.shimPort}/api/stats` : null,
  },
  shimLimits: shim?.limits || null,
  broadcastId: shim?.broadcastId || null,
};
saveState();
console.log(JSON.stringify({ event: 'target-ready', stateFile: join(o.dir, 'state.json'), ...state.urls, pids: state.pids, ready }));

process.stdin.on('data', d => { if (/^q/i.test(String(d).trim())) stop('stdin'); });
if (o.duration > 0) setTimeout(() => stop('duration'), o.duration * 1000);
// Pulse for the runner: shim counters and the current publisher PID (it is restarted if it exits) every 5 s.
setInterval(() => { Object.assign(state, { shimStats: shim?.stats || null, publisherRestarts, chatClients: shim?.chatClients() ?? null, mediamtxLog: mtxStats }); state.pids.publisher = pub.pid; saveState(); }, 5000);
